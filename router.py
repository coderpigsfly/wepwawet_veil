def way_back_soon(rid, words):
    """A few seconds after an answer heard through the audio path (Home Assistant's run done by
    then), read Home Assistant's own record of it and keep the way back on its row (Stats): from
    the answer leaving the router to Home Assistant done with it. Off without Home Assistant's
    address and token, or with integrations: home_assistant: time_way_back_seconds 0."""
    ha = config.section(config.section(SETTINGS, "integrations"), "home_assistant")
    wait = float(ha.get("time_way_back_seconds", 6) or 0)
    url, token = str(ha.get("url") or "").rstrip("/"), config.secret(ha.get("token") or "HA_TOKEN")
    if not wait or not url or not token:
        return
    left = time.time()

    async def later():
        await asyncio.sleep(wait)
        try:
            access.ACCESS.check_outbound(url)
            ms = hadebug.back_ms(await asyncio.to_thread(hadebug.runs, url, token, 8), words, left)
        except Exception as e:
            log.info("  ! the way back: couldn't read Home Assistant's runs: %s", e)
            return
        if ms is not None:
            ACTIVITY.finish(rid, t_back=ms)
    try:
        asyncio.get_running_loop().create_task(later())
    except RuntimeError:          # no event loop (a test)
        pass


