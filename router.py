async def heard_at_home(d, heard, rid, started, body, cpu0, flight, streaming, calls=()):
    """Is what the Off-Platform model heard answered at home? Then her own answer (a response), or her
    question first when it would change something; None: it's Off-Platform's after all, its answer goes on.
    calls: its tool calls: on words it had to correct, she asks first (dump17), never acting on a guess."""
    said = d.get("rewrite") or d["said"]        # a yes to "ask around?" sent the words asked about
    if not heard or clean(heard) == clean(said):
        return None
    ins = "\n\n" + heard_instruction()
    msgs = [dict(m, content=m["content"][:-len(ins)]) if m.get("role") == "system" and str(m.get("content") or "").endswith(ins)
            else m for m in body.get("messages") or [] if not (m.get("role") == "system" and m.get("content") == heard_instruction())]
    for i in range(len(msgs) - 1, -1, -1):
        if msgs[i].get("role") == "user":
            msgs = msgs[:i] + [dict(msgs[i], content=heard)] + msgs[i + 1:]
            break
    d2 = decide(msgs, pending={}, turns=[])
    if d2["path"] not in ("A", "B", "flea") and calls and phases.on("dump17"):
        # it would act on words it had to correct ("put in one whole closet"): she asks first; yes sends what it
        # heard Off-Platform again, to act on what was meant
        log.info("  the Off-Platform model heard \"%s\" as \"%s\" and would act (%s): she asks first", said, heard,
                 ", ".join(c.get("name") or "?" for c in calls))
        line = phrase("router", "heard_as", d["assistant"]).format(meant=heard)
        ask_later(d["assistant"], {"kind": "ask_around", "said": heard})
        record_turn(d["assistant"], d, msgs, "router", line)
        if rid and ACTIVITY:
            try:
                ACTIVITY.finish(rid, answer=f'(heard as "{heard}", would act: asked first)', status=200,
                                ms=round((time.monotonic() - started) * 1000, 1))
            except Exception as e:
                log.info("  ! couldn't log it: %s", e)
        return local_reply(line, streaming)
    if d2["path"] not in ("A", "B", "flea"):
        log.info("  the Off-Platform model heard \"%s\": not answered at home (path %s), its answer goes on", heard, d2["path"])
        return None
    changes = FLEAS.changes(d2["flea"]) if d2["path"] == "flea" else not read_only(d2)
    log.info("  the Off-Platform model heard \"%s\" as \"%s\": %s at home%s", said, heard,
             d2.get("topic") or d2.get("flea"), ", a change: she asks first" if changes else "")
    if rid and ACTIVITY:
        try:
            ACTIVITY.finish(rid, answer=f'(heard as "{heard}": {"asked first" if changes else "answered at home"})', status=200,
                            ms=round((time.monotonic() - started) * 1000, 1))
        except Exception as e:
            log.info("  ! couldn't log it: %s", e)
    if changes:
        line = phrase("router", "heard_as", d["assistant"]).format(meant=heard)
        ask_later(d["assistant"], {"kind": "heard_as", "said": said, "meant": heard})
        record_turn(d["assistant"], d, msgs, "router", line)
        return local_reply(line, streaming)
    keep_heard(said, heard)
    body2 = dict(body, messages=msgs, _veil_heard=said)
    if phases.on("dump21"):        # timed from here: the Off-Platform trip is the row before's (Stats)
        return await answer_chat(body2, time.monotonic(), resources.cpu_seconds(), None)
    return await answer_chat(body2, started, cpu0, None)


