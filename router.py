def twin_of(d):
    """(the other device, seconds ago) when these same words came from another device within
    router: twin_seconds (both woke on one person), else None; this request is noted either way."""
    key, now = clean(d.get("spoken") or d["said"]), time.monotonic()
    was = TWINS.get(key)
    TWINS[key] = (d["assistant"], now)
    for k in [k for k, v in TWINS.items() if now - v[1] > 60]:
        del TWINS[k]
    within = float(_ROUTER.get("twin_seconds", 3) or 0)
    if key and was and was[0] != d["assistant"] and now - was[1] <= within:
        return was[0], now - was[1]
    return None


