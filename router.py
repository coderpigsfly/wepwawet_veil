HEARD_TAG = str(_ROUTER.get("heard_tag") or "").strip()
HEARD_INSTRUCTION = str(_ROUTER.get("heard_instruction") or "").strip()


def heard_split(text, end=False):
    """("found", what it heard, the rest) when the text opens with the HEARD: line; ("wait", None, text)
    while the first line isn't whole yet (end: the answer ended); ("none", None, text) otherwise."""
    s = re.sub(r"^[\s*_#>`]+", "", text or "")
    tag = HEARD_TAG.lower()
    if not s or len(s) < len(tag):
        return ("wait" if not end and tag.startswith(s.lower()) else "none"), None, text
    if not s.lower().startswith(tag):
        return "none", None, text
    if "\n" not in s and not end:
        return "wait", None, text
    line, _, rest = s.partition("\n")
    return "found", line[len(tag):].strip(" *_`\"'\t"), rest.lstrip()


