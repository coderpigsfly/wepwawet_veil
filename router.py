def holding_now():
    """What the router is carrying between requests right now, per device, with ages in seconds:
    its question waiting for an answer (path C), its last topic answered at home (path B), the
    turn record, and whether a sentence would go back Off-Platform. For the Settings page."""
    now = time.time()
    pend, mem, turns = _load_pending(), _load_state(), _load_turns()
    out = {}
    for who in sorted(set(FLAIR.names()) | set(pend) | set(mem) | set(turns)):
        p, m = pend.get(who), mem.get(who)
        out[who] = {
            "pending": dict(kind=p.get("kind"), age=round(now - p.get("time", 0)),
                            alive=now - p.get("time", 0) <= CONTEXT_WINDOW) if p else None,
            "memory": dict(topic=m.get("topic"), said=m.get("said"), age=round(now - m.get("time", 0)),
                           alive=now - m.get("time", 0) <= CONTEXT_WINDOW) if m else None,
            "turns": [{"heard": t.get("heard"), "path": t.get("path"), "engine": t.get("engine"),
                       "age": round(now - float(t.get("time") or 0))} for t in reversed(turns.get(who) or [])],
            "off_platform_conversation": in_gemini_conversation(who),
        }
    return {"devices": out, "context_window": CONTEXT_WINDOW, "gemini_window": GEMINI_CONVERSATION,
            "followup_lookback": FOLLOWUP_LOOKBACK, "followup_max_words": FOLLOWUP_MAX_WORDS}


def decide(messages, fresh=False, pending=None, memory=None, turns=None):
    """What to do with this request, and why. Changes nothing, calls nothing."""
    d = _decide(messages, fresh, pending, memory, turns)
    if d["path"] != "gemini" or not d["said"].strip() or d.get("kind") == "ask_yes":
        return d
    if answering_gemini(messages, d["said"]):
        step(d, "conversation", "a yes or no to the Off-Platform answer's own question: back Off-Platform")
        return d
    flea, fs, how = FLEAS.find(d["said"])
    if flea and how == "all its key words heard" and telling_a_fact(d["said"]):
        step(d, "fleas", f"{flea}'s key words are heard, but the sentence tells a fact rather than asking: not the flea")
        flea = None
    if flea:
        d.update(path="flea", flea=flea, action=flea, score=round(fs, 3))
        step(d, "fleas", f"{flea} {fs:.0%} ({how})")
        return d
    step(d, "fleas", f"none fits (best {fs:.0%}, they answer at {float(FLEAS.doc.get('match_at', 0.8)):.0%})")
    words = without_polite(d["said"])
    talking = bool(words) and in_gemini_conversation(d["assistant"], turns)
    if talking:
        has_verb, has_noun, parts = diagram(words)
        if has_verb and has_noun:
            step(d, "conversation", f"a whole sentence in an Off-Platform conversation ({parts}): "
                                    f"straight back Off-Platform")
            return d
        step(d, "conversation", f"in one, but not a whole sentence ({parts})")
    else:
        step(d, "conversation", f"none (no Off-Platform answer in the last {age_of(time.time() - GEMINI_CONVERSATION)})")
    if not words or polite_addressed(d["said"], words):
        heard = polite_heard(d["said"])
        d.update(path="0", kind="polite", section=polite_section(heard))
        step(d, "shape", f"polite words only ({', '.join(heard) or 'none'}): answered locally "
                        f"from {d['section']}, nothing to do")
        return d
    kind, parts = shape.classify(d["said"], words, NLP, VOCAB.get("requests", {})) if NLP \
        else ("question", "no diagramming")
    if kind == "fragment":
        d.update(path="0", kind="fragment")
        step(d, "shape", f"too little to act on ({parts}): answered locally")
        return d
    if kind == "ask":
        d.update(path="ask", kind="ask_around", heard=" ".join(words))
        step(d, "shape", f"not shaped like a request ({parts}): the router asks before going Off-Platform")
        return d
    step(d, "shape", f"shaped like a request ({kind}): straight Off-Platform")
    return d


