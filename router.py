def learn_command(said):
    """(kind, note): 'who' ("Who answered that?"), 'heard' ("What did you hear?"),
    'record' ("Record that as a miss", maybe with a note), 'note' ("That should have been
    weather"); the note is the words after "should have been". (None, None) otherwise."""
    words = without_filler(said)
    text = " ".join(words)
    lv = VOCAB.get("learn", {})

    def note_in(t):
        for p in sorted(lv.get("should_be", []), key=len, reverse=True):
            pc = clean(p)
            i = (" " + t + " ").find(" " + pc + " ")
            if i >= 0:
                return t[i + len(pc):].strip() or None
        return None

    def loosely(phrase):
        """The phrase's words in order, with at most one stray word before it or between any
        two ("who we answered that", "as who answered that": speech-to-text adds words),
        and at most 2 after."""
        pw, i = phrase.split(), 0
        for n, w in enumerate(pw):
            gap = 1
            while i < len(words) and words[i] != w and gap > 0:
                i, gap = i + 1, gap - 1
            if i >= len(words) or words[i] != w:
                return False
            i += 1
        return len(words) - i <= 2

    for kind, key in (("who", "who_answered"), ("heard", "what_heard")):
        for p in lv.get(key, []):
            pc = clean(p)
            if text == pc or (text.startswith(pc + " ") and len(words) <= len(pc.split()) + 2) \
                    or (len(pc.split()) > 1 and loosely(pc)):
                return kind, None
    rtext = text
    for lead in [clean(x) + " " for x in lv.get("record_leads", ["no", "nope", "actually", "okay", "ok"])]:  # "No, record..."
        if rtext.startswith(lead):
            rtext = rtext[len(lead):]
    for p in lv.get("record_miss", []):
        pc = clean(p)
        if rtext == pc or rtext.startswith(pc + " "):
            return "record", note_in(rtext[len(pc):].strip())
    note = note_in(text)
    if note and any(text.startswith(clean(p)) for p in lv.get("should_be", [])):
        return "note", note
    return None, None


