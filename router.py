# router.py - Wepwawet Veil, the house intent router (its own container, house-router).
# Private AI routing. Leaner context. Smarter handoff.
#
# The flow: Home Assistant hands a request to LiteLLM, which hands it to this router (it's
# listed there as an OpenAI-compatible model). The router answers at home when it can; what
# it can't, it hands back to LiteLLM's fallback model (Gemini), and the answer goes back
# through the router to the device that asked, which speaks it.
#
# Before deciding: who spoke (Oread, when on: veil/speakers.py) and the firewall
# (firewall.yaml: veil/firewall.py). After: her flair, and now and then the person's name.
# Every request is written to the activity log and Gemini's answers to the answer bank
# (data/veil.db: veil/activity.py), for the pages (veil/web.py, port 8771).
#
# Path 0: false wakes and dismissals, answered locally.
# Path A: a topic scored at or above confidence_local (or its noun plus verb agree)
#         -> its service answers locally.
# Path C: an answer to her own question (a pending question in state/pending.json),
#         e.g. "yes" to "Want to hear the rest?"; anything that doesn't answer it drops it.
# Path B: a follow-up to the last topic ("what about Sunday?") -> that topic's service,
#         with the earlier requests as context.
# Everything else is passed through untouched to LiteLLM's fallback model (Gemini).
# One decision function, decide(), is used by real requests and by /explain (testing).
# Knobs, topics, people, services: settings.yaml   Words heard: vocab/*.yaml
# Spoken lines: phrases/*.yaml   Her flair: personality/*.yaml (flair.py)
# Voice maps: connectors/, actions/ (generated)
# Generated by tools/build_scores.py: topics/, scores/, actions/   Secrets: .env

