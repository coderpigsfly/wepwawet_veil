def replies_before(messages):
    """Her earlier replies in HA's history, leaving out her answers to learn questions
    (asking twice in a row still looks back at the real turn)."""
    out, ask = [], None
    for m in messages[:-1]:
        if m.get("role") == "user":
            ask = text_of(m.get("content"))
        elif m.get("role") == "assistant":
            if not (ask and learn_kind(ask)):
                out.append(text_of(m.get("content")))
    return out


def last_real_turn(turns):
    """The newest turn that wasn't a false wake, a fragment or polite words alone (path 0): the
    one "Who answered that?" means, and the one the Off-Platform conversation looks back to."""
    for turn in reversed(turns or []):
        if turn.get("path") != "0":
            return turn
    return None


def learn_reply(kind, turns, messages, assistant):
    """The answer about the last real turn (false wakes skipped), from the turn record."""
    last = last_real_turn(turns)
    skipped = 0                       # false wakes after it: their replies are newer in the history
    for turn in reversed(turns or []):
        if turn is last:
            break
        skipped += 1
    prior = replies_before(messages)
    prior = prior[:len(prior) - skipped] if skipped and len(prior) > skipped else prior
    if last and prior and last.get("answer") and clean(prior[-1])[:60] != clean(last["answer"])[:60]:
        # HA's history shows a reply the router never gave: HA answered that one itself
        return phrase("router", "learn_not_me", assistant), None
    if not last or (not prior and time.time() - last.get("time", 0) > CONTEXT_WINDOW):
        return phrase("router", "learn_nothing", assistant), None
    if kind == "heard":
        return phrase("router", "learn_heard", assistant).format(heard=last["heard"].strip()), last
    names = VOCAB.get("learn", {}).get("engines", {})
    if last.get("engine") == "router":
        return phrase("router", "learn_me", assistant), last
    if last.get("engine") == "bank":         # kept from the Off-Platform model's answers to the same words
        return phrase("router", "learn_bank", assistant).format(model=names.get("gemini") or "the Off-Platform model"), last
    return phrase("router", "learn_engine", assistant).format(
        engine=names.get(last.get("engine"), last.get("engine") or "something")), last


def confident_topic(text):
    """The topic this text would be confidently answered as, or None (same test as decide)."""
    ranked = SCORER.rank(text)
    if not ranked:
        return None
    topic, s, _, why = ranked[0]
    if why == "ok" and s >= CONFIDENCE:
        return topic
    conn = connector_for(topic)
    if conn:
        a, vs, _ = conn.pick_action(text, measured_only=True)
        api = ((conn.map.get("actions") or {}).get(a) or {}).get("api", "")
        if vs >= CONFIDENCE and api.upper().startswith("GET "):
            return topic
    return None


def history_topic(messages):
    """The topic of the most recent earlier request (in what HA sent) that clearly had one,
    plus the requests from there to now (newest first) as context."""
    context = []
    for earlier in earlier_requests(messages)[:FOLLOWUP_LOOKBACK]:
        context.append(earlier)
        topic = confident_topic(earlier)
        if topic:
            return topic, context
    return None, []


def last_topic(messages, assistant, fresh=False, memory=None):
    """(topic, context, where it came from): the topic a follow-up can lean on, only within the
    context window (fresh=True is for testing, where there is no real clock behind the history).
    memory: None -> the router's real memory; {} or a dict -> stand-in (testing)."""
    topic, context = history_topic(messages)
    mem = recall(assistant) if memory is None else (memory or None)
    mem = mem if mem and mem.get("topic") else None      # a stand-in with only the thing she last named: no context
    held = f"the router's last topic at home, {mem['topic']}, {age_of(mem.get('time'))} old" if mem else \
        f"no last topic at home within {age_of(time.time() - CONTEXT_WINDOW)}"
    if topic and (fresh or (mem and mem["topic"] == topic)):
        return topic, context, f"the front end's history ({topic}) and {held}" if not fresh else f"the history ({topic}, testing)"
    if mem and not topic:
        return mem["topic"], [mem["said"]], held + f" (the history's last {FOLLOWUP_LOOKBACK} requests name no topic)"
    if topic:
        return None, [], f"the history names {topic}, but {held}: not used"
    return None, [], held


