def about_asking(said):
    """A longer yes or no to "Want me to ask around?" that talks about the asking itself:
    "No, I don't want you to ask around" -> 'no', "Yes, check with your coven" -> 'yes'
    (the words in vocab/answers.yaml about_asking, matching each assistant's way of asking).
    Anything else that starts with yes or no ("no, what's the weather") stays a new request."""
    words = without_filler(said)
    first = answer_kind(words[0]) if words else None
    if not first:
        return None
    text = " " + " ".join(words) + " "
    asking = VOCAB.get("answers", {}).get("about_asking") or ["ask", "asking"]
    if any(" " + clean(w) + " " in text for w in asking) or (first == "no" and any(
            n in text for n in (" don't ", " dont ", " do not ", " not "))):
        return first
    return None


# ---------- reading lists aloud (any service) ----------
# A service that answers with a list returns "items" plus a "speech" line holding {items}.
# The router reads the first read_list_max, then asks "Want to hear the rest?" (path C).

def join(items):
    items = list(items)
    if phases.on("dump12") and len(items) > 1 and all(str(x).rstrip().endswith((".", "!", "?")) for x in items):
        # things that are sentences (Wikipedia's events) are read as sentences, not run together with commas
        return " ".join(str(x).rstrip() for x in items[:-1]) + " " + str(items[-1]).rstrip().rstrip(".")
    if len(items) <= 1:
        return "".join(items)
    if len(items) == 2:
        return items[0] + " and " + items[1]
    return ", ".join(items[:-1]) + ", and " + items[-1]


def read_list(speech, items, assistant, most=None, start=0):
    """(what she says, items left over). Leftovers mean she ends with the question. most: how many at
    once (a rule's own read length, else read_list_max); start: how many were read before (numbering)."""
    n = int(most) if phases.on("dump14") and most else READ_LIST_MAX
    head, rest = items[:n], items[n:]
    if phases.on("dump14") and READ_LIST_NUMBERS:     # each said with its place, counted across "the rest?"
        head = [f"{start + i + 1}, {x}" for i, x in enumerate(head)]
    line = speech.replace("{items}", join(head))
    if rest:
        line += " " + phrase("router", "list_more", assistant).format(more=len(rest))
        line += " " + phrase("router", "list_ask", assistant)
    return line, rest


