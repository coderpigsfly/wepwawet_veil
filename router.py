def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f) or {}


def load_folder(folder, label):
    """Every .yaml file in a folder, keyed by file name without .yaml."""
    found = {}
    for name in sorted(os.listdir(folder)):
        if name.endswith((".yaml", ".yml")):
            found[name.rsplit(".", 1)[0]] = load_yaml(os.path.join(folder, name))
    log.info("loaded %s files: %s", label, ", ".join(found) or "(none)")
    return found


