def _polite_split(said):
    """(the polite phrases heard, the words left): each phrase matched as whole words, longest
    first, as often as it's said ("bye bye", "thank you thank you"), before filler is taken out,
    so a phrase holding a filler word ("hey there") still counts; then filler and the assistants'
    names come out of what's left."""
    names = PERSONA_WORDS | {ADDRESSED.get()}
    words = [w for w in clean(said).split() if w not in names]
    phrases = sorted({clean(p) for p in VOCAB.get("path0", {}).get("polite_phrases", [])},
                     key=lambda p: len(p.split()), reverse=True)
    found, left, i = [], [], 0
    while i < len(words):
        p = next((p for p in phrases if words[i:i + len(p.split())] == p.split()), None)
        if p:
            found.append(p)
            i += len(p.split())
        else:
            left.append(words[i])
            i += 1
    filler = set(VOCAB.get("path0", {}).get("filler_words", []))
    return found, [w for w in left if w not in filler]


def polite_heard(said):
    """The polite phrases in what was said, longest first ('good morning' before 'morning')."""
    return _polite_split(said)[0]


def polite_section(heard):
    """phrases/router.yaml section for a polite phrase heard alone: polite_<phrase>
    ('morning' also finds polite_good_morning), else the shared 'polite'."""
    lines = PHRASES.get("router", {})
    for p in heard:
        slug = p.replace("'", "").replace(" ", "_")
        for name in (f"polite_{slug}", f"polite_good_{slug}"):
            if name in lines:
                return name
    return "polite"


def without_polite(said):
    """The words left after polite phrases, filler and her name are taken out."""
    return _polite_split(said)[1]


def telling_a_fact(said):
    """Is this sentence telling her something rather than asking (Oct 18: "...we only get our pizza
    at Jade House in Douglasville." brought up the pizza flea by its key word)? No question mark,
    no sentence opening with a question word, and a clause opening with one of vocab/requests.yaml
    telling_starts (we, our, I, my...)."""
    if "?" in said:
        return False
    req = VOCAB.get("requests", {})
    asks, tells = set(req.get("question_words", [])), set(req.get("telling_starts", []))
    clauses = [clean(c).split() for c in re.split(r"[.!,;]+", said) if clean(c)]
    if any(c[0] in asks for c in clauses):
        return False
    return any(c[0] in tells for c in clauses)


def polite_addressed(said, words):
    """A polite phrase said to her with only a name for her besides ("Good morning, sweetheart.",
    Oct 18: taken for a fragment): the words left are all vocab/path0.yaml polite_address."""
    names = {w for p in VOCAB.get("path0", {}).get("polite_address", []) for w in clean(p).split()}
    return bool(words) and bool(polite_heard(said)) and all(w in names for w in words)


def diagram(words):
    """(has a verb, has a noun, the parts of speech) for these words."""
    if NLP is None:
        return True, True, "no diagramming"
    doc = NLP(" ".join(words))
    tags = [t.pos_ for t in doc]
    return bool(VERBS & set(tags)), bool(NOUNS & set(tags)), \
        " ".join(f"{t.text}/{t.pos_}" for t in doc)


def answering_gemini(messages, said):
    """Her last reply (Gemini's) ended in a question and this is a short yes or no to it."""
    last = next((m for m in reversed(messages[:-1]) if m.get("role") == "assistant"), None)
    return bool(last) and text_of(last.get("content")).strip().endswith("?") \
        and answer_kind(said) is not None


def in_gemini_conversation(assistant, turns=None):
    """Did the Off-Platform model (or the bank, in its place) give her last real answer, within
    gemini_conversation_minutes?
    False wakes, fragments and polite words (path 0) don't break the conversation.
    turns: None -> the router's real record; a list -> stand-in (testing)."""
