@app.post("/firewall/check")
async def firewall_check(request: Request):
    """One Home Assistant command: may it run? Body: intent (HassTurnOn...), targets (names,
    areas, entity ids), domains (lock, cover...), text (the words, when HA had them), device_id,
    device_name, satellite_id, platform. Answer: allow, and when not, the message she says."""
    started, cpu0 = time.monotonic(), resources.cpu_seconds()
    b = await request.json()
    intent_type = str(b.get("intent") or "")
    if not fw().has_command_rules():
        return {"allow": True, "why": "the firewall is off or has no rules"}
    assistant = assistant_for_ha(b.get("device_id"), b.get("device_name"), b.get("satellite_id")) or "unknown device"
    text = (b.get("text") or "").strip()
    recent = LAST_WHO.get(assistant) if time.time() - LAST_WHO_TIME.get(assistant, 0) < 60 else None
    if not text and recent is not None:
        who = recent                  # a Gemini tool call: the request it came from was just looked up
    elif OREAD.get("enabled"):
        who = await speakers.lookup(assistant, text, SETTINGS)
    else:
        who = {}
    targets = [str(t) for t in (b.get("targets") or [])]
    hit = fw().check_command(who, assistant, intent_type, targets, b.get("domains") or [], text)
    if not hit and str(b.get("platform") or "conversation") != "conversation" and phases.on("dump16"):
        # asked for by a language model through Home Assistant's tools (not Home Assistant's own agent):
        # what no model may work, judged by what the command does (#11: a lock named "Front Door")
        hit = fw().check_model_command(intent_type, targets, b.get("domains") or [])
    d = {"assistant": assistant, "said": text or f"({intent_type} {', '.join(targets)})", "path": "ha",
         "kind": intent_type, "why": [f"Home Assistant command {intent_type} on {', '.join(targets) or 'nothing named'}"
                                      f" from {b.get('device_name') or b.get('device_id') or 'no device'}"
                                      f" ({b.get('platform') or '?'}); who spoke: {who_label(who)}"]}
    d["cpu0"] = cpu0
    if text and wyoming.SERVERS:          # Home Assistant's own command: Oread's words arrived here
        d["hops"] = wyoming.claim(assistant, text, OREAD.get("max_age_seconds", 20),
                                  OREAD.get("min_word_overlap", 0.5))
        if d["hops"].get("audio_swaps"):
            d["why"][0] += audio_swaps_text(d["hops"])
    if hit:
        line = block_line(hit, assistant)
        d["why"].append(f"firewall: {hit['why']} (rule: {hit['rule'].get('name') or 'unnamed'})")
        log.info("Home Assistant command %s %s (%s): blocked by the firewall (%s): %s",
                 intent_type, targets, assistant, hit["why"], line)
        log_activity(d, who, "home_assistant", line, started, blocked=hit)
        return {"allow": False, "message": line, "why": hit["why"], "rule": hit["rule"].get("name"),
                "assistant": assistant, "who": who_label(who)}
    d["why"].append("no rule stops it: back to Home Assistant")
    log_activity(d, who, "home_assistant", "(allowed; Home Assistant carried it out)", started)
    return {"allow": True, "assistant": assistant, "who": who_label(who)}


