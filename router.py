def cpu_used(d):
    """The router's CPU time (ms) since this request arrived (d["cpu0"]), or None. A request that went
    Off-Platform counts it up to the hand-off (d["cpu_sent"]): the wait for the model isn't the router's
    work, though the process kept doing other things during it (dump17)."""
    if d.get("cpu0") is None:
        return None
    end = d["cpu_sent"] if d.get("cpu_sent") is not None and phases.on("dump17") else resources.cpu_seconds()
    return round((end - d["cpu0"]) * 1000, 1)


