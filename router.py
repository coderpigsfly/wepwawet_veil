def step(d, name, text):
    """One numbered line of the decision's trace."""
    d["why"].append(f"{TRACE.index(name) + 1}. {TRACE_NAMES[name]}: {text}")


def age_of(t):
    s = max(0, round(time.time() - float(t or 0)))
    return f"{s} s" if s < 120 else f"{round(s / 60)} min"

def _decide(messages, fresh=False, pending=None, memory=None, turns=None):
    """What to do with this request, and why. Changes nothing, calls nothing.
    pending, memory: None -> this assistant's saved question and memory;
    {} or a dict -> stand-in (testing), so a real voice test can't change a test's result."""
    said = heard(messages)
    d = {"said": said, "assistant": assistant_name(messages), "path": "gemini",
         "topic": None, "score": None, "action": None, "action_words": [],
         "context": [], "ranked": [], "why": []}
    # her own name, said to her, is filler like "um": only a real name, an assistant with a personality
    # file or instructions opening "<Name> Personality" (Home Assistant's default ones open "You are...",
    # and "you" is no name)
    ADDRESSED.set(d["assistant"] if d["assistant"] in PERSONAS or named_persona(messages) else "")

    if messages and messages[-1].get("role") != "user":
        d["path"] = "tool"
        # how many times this request has gone back and forth for actions: the cloud model's tool
        # calls since the person last spoke (router: off_platform_tool_rounds caps them)
        last_user = max(i for i, m in enumerate(messages) if m.get("role") == "user") if any(
            m.get("role") == "user" for m in messages) else -1
        d["tool_rounds"] = sum(1 for m in messages[last_user + 1:] if m.get("role") == "assistant" and m.get("tool_calls"))
        d["why"].append(f"second trip of an Off-Platform tool call (round {d['tool_rounds']} of {TOOL_ROUNDS}): straight through")
        return d

    # the words first (the Mishearings add-on: the ones marked Use it, learn/swaps.yaml), before any key word
    swapped = []
    said = ADDONS.run("understand", said, {"assistant": d["assistant"], "swapped": swapped})
    if swapped:
        d.update(said=said, heard_raw=heard(messages), swaps=swapped)
    # the words as the person said them: said may become the request an answer goes on with ("Yes."
    # to "Rotisserie diagram?"), but the log, who spoke and the audio path's match go by these
    d["spoken"] = said
    step(d, "words", f'"{said}" on {d["assistant"]}; compared as "{clean(said)}"'
                     + "".join(f'; heard "{h}", used "{m}" (a mishearing marked Use it)' for h, m in swapped))
    kind = path0(said)
    if kind:
        d.update(path="0", kind=kind)
        step(d, "path 0", f"{LOG_LABEL[kind]}: answered at home")
        return d
    waiting = pending if pending is not None else pending_for(d["assistant"])
    if answers_waiting(waiting, said):
        echo = None
        step(d, "path 0", f"answers her waiting question ({waiting.get('kind')}): tried as an answer, not as an echo")
    else:
        echo = echo_of(said, turns if turns is not None else [t for ts in _load_turns().values() for t in ts or []])
    yes, rest = after_echo(said, echo[2]) if echo else (None, None)
    if rest and yes and waiting and leading_answer(f"{yes}. {rest}"):
        from veil import spoken as _sp
        if not (_sp.asked_of_you(rest) or _sp.requested_of_you(rest)):
            rest = None              # "Yes. Thanks.": the yes is the answer, the rest asks for nothing
    if rest:
        # the person's own request after her words came back ("... Is that right? Yes. Could you change the
        # time on that to 3:45?"): that request, her offered thing taken as the one meant (offered, below)
        step(d, "path 0", f"{LOG_LABEL['echo']} {echo[1]} s ago, then the person's own words: \"{rest}\""
                          + (f" (after \"{yes}\")" if yes else ""))
        said = d["said"] = rest
        d["after_yes"] = yes
    elif yes and waiting:
        step(d, "path 0", f"{LOG_LABEL['echo']} {echo[1]} s ago, then an answer of the person's own: \"{yes}\"")
        said = d["said"] = yes
    elif echo:
        d.update(path="0", kind="echo")
        step(d, "path 0", f"{LOG_LABEL['echo']} {echo[1]} s ago ({echo[0]:.2f} of the words): not answered")
        return d
    step(d, "path 0", "not a false wake, a dismissal or an echo")

    lk, note = learn_command(said)
    if lk in ("who", "heard"):
        t = (_load_turns().get(d["assistant"]) or []) if turns is None else turns
        speech, turn = learn_reply(lk, t, messages, d["assistant"])
        d.update(path="learn", kind=lk, speech=speech, learn_turn=turn)
        step(d, "learn", f"learn: {'who answered that' if lk == 'who' else 'what did you hear'}, "
                        f"about the turn before")
        return d
    if lk in ("record", "note"):
        d.update(path="learn", kind=lk, note=note)
        step(d, "learn", f"learn: {'record that as a miss' if lk == 'record' else 'a note'}"
                        + (f" (should have been: {note})" if note else ""))
        return d

    step(d, "learn", "not a learn command")
    switch = trainer_command(said)
    if switch:          # "Trainer mode", "Turn on trainer mode for Mara" (#29): who may is checked on the answer's side
        d.update(path="trainer", kind="switch", turn=switch[0], target=switch[1])
        step(d, "learn", f"trainer mode, said by voice: {switch[0] or 'its state'} for {switch[1] or 'whom?'}")
        return d
    p = pending_for(d["assistant"]) if pending is None else pending
    if p:
        step(d, "question", f"waiting: {p.get('kind')}" + (f", asked {age_of(p.get('time'))} ago" if p.get("time") else ""))
    else:
        step(d, "question", "none waiting" + ("" if pending is not None else f" (they wait {age_of(time.time() - CONTEXT_WINDOW)})"))
    lead = leading_answer(said) if p and not answer_kind(said) and (
        p.get("kind") in ("list_rest", "ask_around") or p.get("mode") == "confirm") else None
    if lead:
        step(d, "question", f"'{lead}' first, then words that ask for nothing: '{lead}' answers it")
        said = lead
    if p and p.get("kind") == "series" and opens_new_request(p, said):
        p = None
        d["pending_dropped"] = True
        step(d, "question", "the 'anything else?' is left: this opens a new request (an action word and a new thing)")
    if p and p.get("kind") == "series":
        line, nxt, changes = series.answer(p, said, now_local(), series_say(d["assistant"]),
                                           VOCAB.get("answers", {}).get("stop", []))
        if line is not None:
            d.update(path="C", kind="series", topic=p.get("topic"), pending=p,
                     series_line=line, series_next=nxt, series_changes=changes)
            step(d, "question", f"path C: answers the 'anything else?' for {p.get('name')} "
                            f"(adds: {', '.join(changes) or 'nothing'})")
            return d
        p = None
        d["pending_dropped"] = True
        step(d, "question", "the 'anything else?' is left unanswered: handled as a new request")
    if p and p.get("kind") == "object":
        # her "in reference to what?": the answer is the thing, put after the verb ("what does Mara have" +
        # "chores"), and the whole request decided afresh; no, or a request of its own, leaves it
        words = without_filler(said)
        if answer_kind(said) == "no":
            d.update(path="C", kind="no", pending=p)
            step(d, "question", "no to 'in reference to what?': nothing more")
            return d
        if words and len(words) <= ADD_NAME_MAX_WORDS and not own_request(None, None, said):
            whole = " ".join(x for x in (p.get("head"), " ".join(words), p.get("tail")) if x)
            msgs = [m for m in messages if m.get("role") == "system"][:1] + [{"role": "user", "content": whole}]
            d2 = decide(msgs, fresh, {}, memory, [])
