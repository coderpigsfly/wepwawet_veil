def stream_chunks(text):
    """Her words as the pieces of a streamed chat answer (OpenAI's format)."""
    rid = "chatcmpl-" + uuid.uuid4().hex
    now = int(time.time())

    def chunk(delta, finish=None):
        data = {"id": rid, "object": "chat.completion.chunk",
                "created": now, "model": MODEL,
                "choices": [{"index": 0, "delta": delta,
                             "finish_reason": finish}]}
        return "data: " + json.dumps(data) + "\n\n"

    return [chunk({"role": "assistant"}), chunk({"content": text}), chunk({}, "stop"), "data: [DONE]\n\n"]


def local_reply(text, streaming):
    text = flairs.strip(text)          # a [[slot]] is never spoken, flair or not
    rid = "chatcmpl-" + uuid.uuid4().hex
    now = int(time.time())

    if streaming:
        def stream():
            yield from stream_chunks(text)

        return StreamingResponse(stream(), media_type="text/event-stream")

    return JSONResponse({
        "id": rid, "object": "chat.completion", "created": now, "model": MODEL,
        "choices": [{"index": 0, "finish_reason": "stop",
                     "message": {"role": "assistant", "content": text}}],
        "usage": {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0},
    })


