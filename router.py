def leading_yes(said):
    """(yes or no, the request after it) when a request opens with one ("Yes, could you change the time on that
    to 3:45?", Oct 21: her speaker stopped when he spoke, so it came as one sentence, not after her echo), else
    (None, said)."""
    words = said.strip().split()
    for n in (1, 2):              # "Yes, could you": one word first; "Of course, could you": two
        if len(words) <= n + 2:
            continue
        kind = answer_kind(" ".join(words[:n]).rstrip(",.!"))
        if kind in ("yes", "no"):
            return kind, " ".join(words[n:]).lstrip(",. ")
    return None, said


def leading_answer(said):
    """A yes or no said first, then room talk that asks for nothing ("Yes. I don't think you're
    not sure." to "Rotisserie diagram?", Oct 18): the first sentence, when it's a short answer
    and the rest names no topic and none of an app's own things. None otherwise (so "No. What's
    the weather?" and "Yes. Mark check pool filter done." stay requests)."""
    parts = [x.strip() for x in re.split(r"(?<=[.?!])\s+", said.strip()) if x.strip()]
    if len(parts) < 2 or not answer_kind(parts[0]):
        return None
    rest = " ".join(parts[1:])
    if SCORER.rank(rest) or any(c.names_thing(rest) for c in CONNECTORS.values()):
        return None
    return parts[0].rstrip(".?!")


