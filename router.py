def path0(said):
    words = clean(said)
    letters = sum(c.isalnum() for c in words)
    if letters <= int(SETTINGS.get("false_wake_max_letters", 1)):
        return "false_wake"
    kept = without_filler(said)
    if not kept:
        return "false_wake"
    # Dismissed if what was said ENDS with a dismiss phrase (whole words),
    # so noise before "never mind" still counts.
