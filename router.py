def phrase(file, section, assistant):
    """A line from phrases/<file>.yaml, section, for this assistant
    (falling back to the 'any' list)."""
    sec = PHRASES.get(file, {}).get(section, {}) or {}
    who = assistant if sec.get(assistant) else "any"
    lines = sec.get(who) or []
    if not lines:
        return "Mm."
    key = (file, section, who)
    if key not in _bags:
        _bags[key] = ShuffleBag(lines)
    return _bags[key].draw()


