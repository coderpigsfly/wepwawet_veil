def opens_new_request(p, said):
    """While she waits on "anything else?", is this a new request instead of an answer? It opens
    with one of the app's own action words ("REMIND me to call the plumber") and names a new thing
    of two words or more ("call the plumber"). "Remind me an hour before" names nothing new: an
    answer. Any app: its voice map's words and the shared name reader (veil/spoken.py)."""
    conn = connector_for(p.get("topic") or "")
    if not conn:
        return False
    words = without_filler(said)
    action, score, found = conn.pick_action(" ".join(words))
    if not action or not found:
        return False
    lead = " ".join(words[:3])
    if not any(lead.startswith(f) or (" " + f + " ") in (" " + lead + " ") for f in found):
        return False
    thing = conn.spoken_value(said, action)
    from veil import spoken as _spoken
    # a thing to do of its own (an action with its noun: "take Newton to the vet"), not just its fields
    return len(thing.split()) >= 2 and _spoken.is_task(thing) and not names_its_extra(p, said, thing, conn)


def names_its_extra(p, said, thing, conn):
    """A patch (Oct 15), narrow on purpose until there's real sentence understanding: while
    "anything else?" waits on an item, a sentence naming one of its extras by the extra's own words
    ("PUT a NAG every ten minutes on the chore Sam is the mayor") answers it, even opening with an
    action word, unless the thing it names is another item ("remind me to call the plumber": a new
    one). The same item: the voice map's match_min of its words, or nothing named but the extra and
    a word pointing at it ("add a due date to THAT", Oct 17: it went to Gemini, which made the
    chore again). Off with the service's option extras_win_while_asking (its Defaults tab), and for
    a voice map with no match_min."""
    svc = (SCORER.topics.get(p.get("topic") or "") or {}).get("service")
    mm = conn.hand.get("match_min")
    if mm is None or not ((SERVICES.get(svc) or {}).get("options") or {}).get("extras_win_while_asking"):
        return False
    extras = {n: f for n, f in (p.get("fields") or {}).items() if f.get("kind") == "extra"}
    if not series.F.parse_answer(said, extras, now_local())["named"]:
        return False
    own = {w for f in extras.values() for x in f.get("words") or [] for w in str(x).lower().split()}
    if not set(re.findall(r"[a-z']+", thing.lower())) - own - rules.this_words() - connector.STRIP_AWAY:
        return True
    return speakers.overlap(thing, p.get("name") or "") >= float(mm)


