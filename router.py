def opens_on_app_things(said):
    """[(topic, connector, action, words)]: every app where what was said opens with one of its
    action words and names one of its own things. One: it's that app's. More than one: she asks
    which (never the first in a list). Any app's connector can tell. A user rule that changes something
    is never reached this way: it stays inside its topic (a topic word, or a follow-up in its context);
    one that only reads is ("When is Easter?", by the sentence's noun)."""
    out = []
    words = without_filler(said)
    for topic in SCORER.topics:
        conn = connector_for(topic)
        if not conn:
            continue
        action, score, found = conn.pick_action(" ".join(words))
        if not action or not found:
            continue
        # one of its action words starts within the first three words ("how many days until", four words long, too)
        if not any((" ".join(words[i:]) + " ").startswith(f + " ") for f in found for i in range(min(3, len(words)))):
            continue
        if action in getattr(conn, "rules", {}) and conn.changes(action):
            continue          # a user rule that changes something stays inside its topic ("rename that")
        # the whole sentence, or its noun ("When is Easter?": Easter, one of the calendar's things)
        noun = spoken_nouns(said)
        if conn.names_thing(said) or (noun and conn.names_thing(noun)):
            out.append((topic, conn, action, found))
    return out


