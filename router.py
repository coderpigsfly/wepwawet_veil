IN_FLIGHT = {}      # a request being answered (its whole body, hashed) -> its answer, once sent


@app.post("/v1/chat/completions")
async def chat(request: Request):
    """The chat door. The same request coming in again while it's still being answered (Oct 17:
    LiteLLM gave up waiting after its timeout and sent it again, so Gemini was asked twice) isn't
    decided or sent out again: it waits for the first one's answer and gets that same answer, and
    the first one's row counts it (Stats: Sent again)."""
    started, cpu0 = time.monotonic(), resources.cpu_seconds()
    body = await request.json()
    if phases.on("dump20") and body.get("model") and body.get("model") != MODEL:
        return await pass_through(body)        # another model: LiteLLM's, as it came
    key = hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()
    if key in IN_FLIGHT:
        again = await answer_again(key)
        if again is not None:
            return again
    flight = IN_FLIGHT[key] = {"done": asyncio.Event()}
    try:
        reply = await answer_chat(body, started, cpu0, flight)
    except BaseException:
        landed(key, flight, None)
        raise
    return kept(reply, key, flight)


def landed(key, flight, parts):
    """A request's answer has gone (parts: what was sent), or never will (None)."""
    if IN_FLIGHT.get(key) is flight:
        del IN_FLIGHT[key]
    flight["parts"] = parts
    flight["done"].set()


def kept(reply, key, flight):
    """The answer as it leaves, kept for a repeat of the same request; a stream once it's all sent."""
    if not isinstance(reply, StreamingResponse):
        landed(key, flight, ([reply.body], reply.media_type, reply.status_code, False))
        return reply
    inner, pieces = reply.body_iterator, []

    async def passing():
        whole = False
        try:
            async for piece in inner:
                pieces.append(piece)
                yield piece
            whole = True
        finally:
            landed(key, flight, (pieces, reply.media_type, reply.status_code, True) if whole else None)

    reply.body_iterator = passing()
    return reply


async def answer_again(key):
    """The same request again while it's being answered: the first one's answer once it's sent, or
    None (it failed, or was cut off part way: this one is answered on its own)."""
    flight = IN_FLIGHT[key]
    log.info("the same request again, while it's still being answered: waiting for that answer")
    try:
        await asyncio.wait_for(flight["done"].wait(), TIMEOUT)
    except asyncio.TimeoutError:
        landed(key, flight, None)
    if not flight.get("parts"):
        log.info("  ! the first one's answer didn't go out whole: this one is answered on its own")
        return None
    pieces, media, status, streamed = flight["parts"]
    log.info("  -> the same answer again (not decided or sent out twice)")
    if ACTIVITY:
        try:
            ACTIVITY.repeated(flight.get("rid"))
        except Exception as e:
            log.info("  ! couldn't count the repeat: %s", e)
    if streamed:
        return StreamingResponse(iter(pieces), media_type=media, status_code=status)
    return Response(content=pieces[0], media_type=media, status_code=status)


