# ---------- how the Off-Platform model heard it (dump13) ----------
# It writes first, on its own line, the request as it understood it, misheard words corrected (router:
# heard_instruction). That line is never passed on. When what it heard is answered at home, it's
# answered here instead (a change asks first: "I think you meant ... Shall I?"), and kept as a
# mishearing on the Mishearings page, where Use it fixes it before anything is decided next time.

HEARD_TAG = str(_ROUTER.get("heard_tag") or "").strip()
HEARD_INSTRUCTION = str(_ROUTER.get("heard_instruction") or "").strip()


def heard_split(text, end=False):
    """("found", what it heard, the rest) when the text opens with the HEARD: line; ("wait", None, text)
    while the first line isn't whole yet (end: the answer ended); ("none", None, text) otherwise."""
    s = re.sub(r"^[\s*_#>`]+", "", text or "")
    tag = HEARD_TAG.lower()
    if not s or len(s) < len(tag):
        return ("wait" if not end and tag.startswith(s.lower()) else "none"), None, text
    if not s.lower().startswith(tag):
        return "none", None, text
    if "\n" not in s and not end:
        return "wait", None, text
    line, _, rest = s.partition("\n")
    return "found", line[len(tag):].strip(" *_`\"'\t"), rest.lstrip()


def changes_something(said):
    """Does what was said open with, or hold, one of an app's change words (its actions that aren't a GET)?"""
    for conn in CONNECTORS.values():
        try:
            action, score, words = conn.pick_action(said)
            if action and words and conn.changes(action):
                return True
        except Exception:
            continue
    return False


