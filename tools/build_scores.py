#!/usr/bin/env python3
# tools/build_scores.py - builds every topic in settings.yaml from the datasets.
# Run from ~/docker/house-router:
#   python3 tools/build_scores.py build           generate topics/ and scores/ for every topic
#   python3 tools/build_scores.py labels          every dataset label, and which topic claims it
#   python3 tools/build_scores.py refresh [name]  re-download sources from their URLs
#
# For each topic declared in settings.yaml:
#   1. find its labels in every source (by name, or where its seed words concentrate)
#   2. generate its tree: doors from words that point strongly to it, tier 2 groups
#      from its own slot labels, when/who groups from the shared slot roles
#   3. measure: doors alone; every other word with a door
#   4. write topics/<name>.yaml (the tree) and scores/<name>.yaml (the numbers)

import json
import os
import re
import sys
import tarfile
import tempfile
import time
import urllib.request
from collections import Counter, defaultdict

import yaml

SOURCES_FILE = "tools/sources.yaml"
if not os.path.exists(SOURCES_FILE):      # a fresh clone before the first start: the starting copy
    SOURCES_FILE = "defaults/tools/sources.yaml"
TOPICS_DIR = "topics"
SCORES_DIR = "scores"
SETTINGS_FILE = "settings.yaml"
TREE_SECTIONS = ("doors", "about", "when", "who")
GENERATED = "# GENERATED by tools/build_scores.py - do not edit. Rerun the tool instead.\n"
HOLD_OUT = 0          # tools/test_scores.py --held-back: every HOLD_OUT-th doors sentence is kept out of the build


def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f) or {}


SOURCES = load_yaml(SOURCES_FILE)["sources"]   # tools/datasets.py reads the same file
SETTINGS = load_yaml(SETTINGS_FILE) if os.path.exists(SETTINGS_FILE) else {}
K = lambda name, default: type(default)(SETTINGS.get(name, default))
MIN_SEEN = K("min_seen", 3)
STRONG_MIN = K("door_strong_min", 0.90)
NEAR_MIN = K("door_near_min", 0.80)
DOOR_MIN = K("door_min", 0.70)
DOOR_MIN_HITS = K("door_min_hits", 10)
SLOT_MIN = K("slot_min", 2)
SLOT_MAX = K("slot_max", 60)
SEED_MIN = K("seed_min", 5)
SEED_SHARE = K("seed_share", 0.25)
SEED_COVER = K("seed_cover", 0.20)   # a label a seed word claims: this share of its own sentences hold a seed
THIN_MIN = K("thin_min", 300)
OWN_SHARE = K("own_words_share", 0.90)      # a topic no dataset knows: its seed words count this strongly


# ---------- reading datasets into one common shape (tools/datasets.py) ----------

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
