# ---------- topics ----------

def declared_topics():
    return SETTINGS.get("topics") or {}


def load_topics():
    """The generated topic files (used by the test tool and the router)."""
    topics = {}
    if os.path.isdir(TOPICS_DIR):
        for n in sorted(os.listdir(TOPICS_DIR)):
            if n.endswith((".yaml", ".yml")):
                t = load_yaml(os.path.join(TOPICS_DIR, n))
                topics[t.get("topic", n.rsplit(".", 1)[0])] = t
    return topics


def claims(topic, source, label):
    """Does this topic claim this dataset label?"""
    return label in ((topic.get("learn_from") or {}).get(source) or [])


def matcher(word):
    return re.compile(r"\b" + re.escape(word) + r"\b")


def label_tokens(label):
    spaced = re.sub(r"([a-z])([A-Z])", r"\1 \2", label)
    return set(re.split(r"[\s_\-]+", spaced.lower()))


def name_labels(name, data):
    """Labels whose name matches the topic name, per source."""
    names = {name.lower(), name.lower().rstrip("s"), name.lower() + "s"}
    found = {}
    for src, rows in data.items():
        hit = sorted(lab for lab in {r["label"] for r in rows} if label_tokens(lab) & names)
        if hit:
            found[src] = hit
    return found


def find_labels(name, conf, data, taken=frozenset()):
    """Labels each source has for this topic: by name, or where seed words concentrate.
    A seed word cannot claim a label another declared topic matches by name (taken), nor a label
    whose own sentences seldom hold any of the seeds (seed_cover): so "born" alone doesn't bring in a
    catch-all intent (general, news, qa) and with it every word it holds."""
    names = {name.lower(), name.lower().rstrip("s"), name.lower() + "s"}
    seeds = [s.lower() for s in (conf.get("seed") or [])]
    found = {}
    for src, rows in data.items():
        chosen = {lab for lab in {r["label"] for r in rows} if label_tokens(lab) & names}
        by_name = set(chosen)
        for seed in seeds:
            pat = matcher(seed)
            where = Counter(r["label"] for r in rows if pat.search(r["text"]))
            total = sum(where.values())
            if total >= SEED_MIN:
                for lab, n in where.items():        # every label with a real share of this word
                    if n >= SEED_MIN and n / total >= SEED_SHARE and (src, lab) not in taken:
                        chosen.add(lab)
        pats = [matcher(s) for s in seeds]
        for lab in sorted(chosen - by_name):
            own = [r for r in rows if r["label"] == lab]
            held = sum(1 for r in own if any(p.search(r["text"]) for p in pats))
            if own and held / len(own) < SEED_COVER:
                chosen.discard(lab)            # the seed is a guest there, not what the label is about
        chosen.discard("out_of_scope")
        chosen -= set(SOURCES[src].get("never_claim") or [])   # conversation-control intents
        if chosen:
            found[src] = sorted(chosen)
    return found


def tree_words(tree):
    """{word: [where it lives...]} for every word in the tree."""
    found = {}

    def walk(node, path):
        if isinstance(node, dict):
            for k, v in node.items():
                walk(v, f"{path}.{k}")
        elif isinstance(node, list):
            for item in node:
                walk(item, path)
        elif isinstance(node, str):
            found.setdefault(node.lower(), []).append(path)

    for section in TREE_SECTIONS:
        if section in tree:
            walk(tree[section], section)
    return found


def door_class(share):
    if share is None:
        return "unknown"
    if share >= STRONG_MIN:
        return "strong"
    if share >= NEAR_MIN:
        return "near_strong"
    return "tentative"


# ---------- generating a topic's tree from the data ----------

def generate_tree(conf, learn, data):
    claimed = lambda src, label: label in learn.get(src, [])
    door_rows = [(n, r) for n in data if "doors" in SOURCES[n]["use"] for r in data[n]]

    # doors: words in many topic sentences that point strongly to the topic
    tok_seen, tok_hit = Counter(), Counter()
    for n, r in door_rows:
        hit = claimed(n, r["label"])
        for tok in set(re.findall(r"[a-z']+", r["text"])):
            tok_seen[tok] += 1
            tok_hit[tok] += hit
    doors = {tok for tok, h in tok_hit.items()
             if h >= DOOR_MIN_HITS and len(tok) > 2 and h / tok_seen[tok] >= DOOR_MIN}
    doors |= {w.lower() for w in (conf.get("always_tentative") or [])}
    doors |= {w.lower() for w in (conf.get("seed") or [])}       # your words are always doors

    # tier 2, when and who: labeled values from the topic's sentences
    groups = {"about": defaultdict(Counter), "when": defaultdict(Counter), "who": defaultdict(Counter)}
    for n in data:
        src = SOURCES[n]
        role_of = {lab: role for role, labs in (src.get("roles") or {}).items() for lab in (labs or [])}
        ignore = set(src.get("ignore") or [])
        for r in data[n]:
            if not claimed(n, r["label"]):
                continue
            for slot, value in r["parts"]:
                if slot in ignore or len(value) < 2 or len(value.split()) > 3:
                    continue
                role = role_of.get(slot)
                if role == "where":
                    continue                  # places belong to the service, not the router
                groups[role if role in ("when", "who") else "about"][slot][value] += 1

    def keep(cnt):
        vals = [v for v, c in cnt.items() if c >= SLOT_MIN]
        return sorted(vals, key=lambda v: -cnt[v])[:SLOT_MAX]

    tree = {"doors": sorted(doors)}
    for section, by_slot in groups.items():
        kept = {slot: keep(cnt) for slot, cnt in sorted(by_slot.items())}
        kept = {slot: vals for slot, vals in kept.items() if vals}
        if kept:
            tree[section] = kept
    return tree


# ---------- build ----------

def write_topic(tname, topic, doors, results, sources):
    """topics/<name>.yaml (the tree) and scores/<name>.yaml (the numbers)."""
    stamp = time.strftime("%Y-%m-%d %H:%M")
    with open(os.path.join(TOPICS_DIR, f"{tname}.yaml"), "w") as f:
        f.write(GENERATED)
        yaml.safe_dump({"generated": stamp, **topic}, f, sort_keys=False, allow_unicode=True, width=100)
    out = {
        "topic": tname, "generated": stamp,
        "settings": {"min_seen": MIN_SEEN, "door_strong_min": STRONG_MIN, "door_near_min": NEAR_MIN,
                     "door_min": DOOR_MIN, "door_min_hits": DOOR_MIN_HITS},
        "sources": sources,
        "doors": doors,
        "words": results,
    }
    with open(os.path.join(SCORES_DIR, f"{tname}.yaml"), "w") as f:
        f.write(GENERATED)
        yaml.safe_dump(out, f, sort_keys=False, allow_unicode=True, width=100)
    print(f"  wrote topics/{tname}.yaml and scores/{tname}.yaml")


def build_own(tname, conf, door_rows):
    """A topic no dataset knows (feast days): built from its own seed words, each a door counted
    as yours (own_words_share), like the words you add to a voice map. Each word's count in the
    datasets' sentences, all of other topics, says how often it may pull in someone else's request."""
    guard = {w.lower() for w in (conf.get("always_tentative") or [])}
    seeds = sorted({w.lower() for w in (conf.get("seed") or [])} | guard)
    if not seeds:
        print(f"  ! no labels found for '{tname}' in any source, and no seed words of its own - add seed words, or a new source")
        return
    print(f"  no labels found in any source: built from its own seed words, each counted as yours ({OWN_SHARE:.0%})")
    results, doors = {}, {}
    for word in seeds:
        pat = matcher(word)
        seen = sum(1 for _, r in door_rows if pat.search(r["text"]))
        cls = "tentative" if word in guard else door_class(OWN_SHARE)
        results[word] = {"where": ["doors"], "measure": "alone", "share": OWN_SHARE, "share_alone": None,
                         "share_with_door": None, "seen": seen, "topic_seen": 0, "depth_seen": 0, "basis": "yours",
                         "per_source": {}, "door_class": cls + (" (always_tentative)" if word in guard else "")}
        doors.setdefault(cls, []).append(f"{word} {OWN_SHARE:.0%}" + (" (guard)" if word in guard else ""))
    topic = {"topic": tname, "service": conf.get("service"), "learn_from": {},
             "always_tentative": conf.get("always_tentative") or [], "doors": seeds}
    write_topic(tname, topic, doors, results, {})
    others = [f"{w} ({r['seen']})" for w, r in results.items() if r["seen"]]
    if others:
        print(f"  in other topics' sentences: {', '.join(others)} - each may pull in their requests")
    print("  doors, yours:")
    for cls in ("strong", "near_strong", "tentative"):
        if cls in doors:
            print(f"    {cls:12} {', '.join(doors[cls])}")

def build():
    print("Loading sources:")
    data = load_all_sources()
    os.makedirs(TOPICS_DIR, exist_ok=True)
    os.makedirs(SCORES_DIR, exist_ok=True)
    door_rows = [(n, r) for n in data if "doors" in SOURCES[n]["use"] for r in data[n]]
    if HOLD_OUT:          # the held-back part is what the test scores, never what the scores were learned from
        door_rows = [x for i, x in enumerate(door_rows) if i % HOLD_OUT]

    by_name = {t: name_labels(t, data) for t in declared_topics()}
    for tname, conf in declared_topics().items():
        conf = conf or {}
        print(f"\n=== {tname} ===")
        taken = {(s, l) for other, m in by_name.items() if other != tname
                 for s, labs in m.items() for l in labs}
        # your words first: a topic set to datasets: false (Seed Topics) is built from them alone
        learn = find_labels(tname, conf, data, taken) if conf.get("datasets", True) is not False else {}
        if not learn:
            build_own(tname, conf, door_rows)
            continue
        print("  labels found: " + "; ".join(f"{s}: {', '.join(l)}" for s, l in learn.items()))

        topic = {"topic": tname, "service": conf.get("service"), "learn_from": learn,
                 "always_tentative": conf.get("always_tentative") or []}
        topic.update(generate_tree(conf, learn, data))
        words = tree_words(topic)

        topic_door_rows = sum(1 for n, r in door_rows if claims(topic, n, r["label"]))
        depth_rows = [r for n in data if "depth" in SOURCES[n]["use"]
                      for r in data[n] if claims(topic, n, r["label"])]
        if topic_door_rows < THIN_MIN:
            print(f"  ! thin data: only {topic_door_rows} topic sentences in the doors sources"
                  f" (thin_min {THIN_MIN}) - consider adding a source")

        # which sentences already contain one of this topic's doors
        door_pats = [(w, matcher(w)) for w, wh in words.items() if "doors" in wh]
        doors_in = [{w for w, p in door_pats if p.search(r["text"])} for _, r in door_rows]
        has_door = [bool(d) for d in doors_in]

        # measure every word: doors alone, everything else with a door
        results = {}
        for word, wheres in words.items():
            pat = matcher(word)
            is_door = "doors" in wheres
            seen = hits = alone_seen = alone_hits = with_seen = with_hits = 0
            per_source = {}
            for i, (n, r) in enumerate(door_rows):
                if not pat.search(r["text"]):
                    continue
                hit = claims(topic, n, r["label"])
                alone_seen += 1
                alone_hits += hit
                if is_door and doors_in[i] - {word}:      # another door already opened the path
                    with_seen += 1
                    with_hits += hit
                if is_door or has_door[i]:
                    seen += 1
                    hits += hit
                    s = per_source.setdefault(n, [0, 0])
                    s[0] += 1
                    s[1] += hit
            depth_seen = sum(1 for r in depth_rows if pat.search(r["text"]))
            measured = seen >= MIN_SEEN
            results[word] = {
                "where": wheres,
                "measure": "alone" if is_door else "with a door",
                "share": round(hits / seen, 3) if measured else None,
                "share_alone": round(alone_hits / alone_seen, 3) if alone_seen else None,
                "share_with_door": round(with_hits / with_seen, 3)
                    if is_door and with_seen >= MIN_SEEN else None,
                "seen": seen, "topic_seen": hits, "depth_seen": depth_seen,
                "basis": "measured" if measured else "borrowed",
                "per_source": {k: f"{v[1]}/{v[0]}" for k, v in per_source.items()},
            }

        # borrowing: thin or unseen words take their group's average, then their tier's
        def group_average(path):
            vals = [r["share"] for r in results.values()
                    if r["basis"] == "measured"
                    and any(w == path or w.startswith(path + ".") for w in r["where"])]
            return round(sum(vals) / len(vals), 3) if vals else None

        for word, r in results.items():
            if r["basis"] == "borrowed":
                path = r["where"][0]
                avg = group_average(path) or group_average(path.split(".")[0])
                r["share"] = avg
                if avg is None:
                    r["basis"] = "none"

        # door strength from the data (always_tentative stays tentative)
        guard = {w.lower() for w in topic["always_tentative"]}
        doors = {}
        for word, r in results.items():
            if "doors" not in r["where"]:
                continue
            cls = "tentative" if word in guard else door_class(r["share"])
            r["door_class"] = cls + (" (always_tentative)" if word in guard else "")
            share = f"{r['share']:.0%}" if r["share"] is not None else "?"
            doors.setdefault(cls, []).append(f"{word} {share}" + (" (guard)" if word in guard else ""))

        write_topic(tname, topic, doors, results, {n: len(data[n]) for n in data})

        # short summary
        measured = sum(1 for r in results.values() if r["basis"] == "measured")
        borrowed = sum(1 for r in results.values() if r["basis"] == "borrowed")
        none = sum(1 for r in results.values() if r["basis"] == "none")
        print(f"  topic sentences: {topic_door_rows} in doors sources, {len(depth_rows)} in depth sources")
        print(f"  words: {len(results)} ({measured} measured, {borrowed} borrowed, {none} no data)")
        for section in ("about", "when", "who"):
            if section in topic:
                print(f"  {section}: " + ", ".join(f"{slot} ({len(v)})" for slot, v in topic[section].items()))
        print("  doors, as measured:")
        for cls in ("strong", "near_strong", "tentative", "unknown"):
            if cls in doors:
                print(f"    {cls:12} {', '.join(doors[cls])}")

    return data


# ---------- connectors: the voice map for services we don't own ----------

CONNECTORS_DIR = "connectors"
ACTIONS_DIR = "actions"
VERB_MIN_HITS = K("verb_min_hits", 5)
VERB_MIN = K("verb_min", 0.60)
DETAIL_MIN = K("detail_min", 0.50)
VERB_MAX = K("verb_max", 15)


def fetch_spec(url):
    try:
        with urllib.request.urlopen(url, timeout=10) as f:
            text = f.read().decode("utf-8")
        try:
            return json.loads(text)
        except ValueError:
            doc = yaml.safe_load(text)          # OpenAPI allows YAML too
            if not isinstance(doc, dict):
                raise ValueError("its spec isn't JSON or YAML that can be read")
            return doc
    except Exception as e:
        print(f"  ! could not read spec {url}: {e}")
        return None


def intent_of(r):
    return r.get("intent") or r["label"]


def build_connectors(data):
    """For every connectors/*.yaml: check its commands against the service's spec,
    measure each action's verb words, and write actions/<service>.yaml."""
    if not os.path.isdir(CONNECTORS_DIR):
        return
    os.makedirs(ACTIONS_DIR, exist_ok=True)
    topics = load_topics()
    services = SETTINGS.get("services") or {}
    for n in sorted(os.listdir(CONNECTORS_DIR)):
        if not n.endswith((".yaml", ".yml")):
            continue
        conn = load_yaml(os.path.join(CONNECTORS_DIR, n))
        sname = conn.get("service")
        svc = services.get(sname) or {}
        print(f"\n=== connector: {sname} ===")

        # 1. the service's own list of commands
        spec = fetch_spec(svc["spec"]) if svc.get("kind") == "openapi" and svc.get("spec") else None
        ops = {}
        if spec:
            for path, methods in (spec.get("paths") or {}).items():
                for m, op in methods.items():
                    ops[f"{m.upper()} {path}"] = op
            print(f"  spec: {len(ops)} commands read")

        # 2. the topic's sentences, where the actions compete for each word
        topic = topics.get(conn.get("topic"))
        if not topic:
            print(f"  ! topic '{conn.get('topic')}' isn't built - add it to settings.yaml and rebuild")
            continue
        rows = [(src, r) for src in data for r in data[src] if claims(topic, src, r["label"])]
        tok_all = Counter()
        for _, r in rows:
            for tok in set(re.findall(r"[a-z']+", r["text"])):
                tok_all[tok] += 1

        # words that mostly sit inside labeled slots are details (nouns), never verbs
        in_slot, with_slots = Counter(), Counter()
        for _, r in rows:
            if not r["parts"]:
                continue
            slot_toks = {t for _, v in r["parts"] for t in re.findall(r"[a-z']+", v)}
            for tok in set(re.findall(r"[a-z']+", r["text"])):
                with_slots[tok] += 1
                in_slot[tok] += tok in slot_toks
        details = {t for t, n in with_slots.items()
                   if n >= MIN_SEEN and in_slot[t] / n >= DETAIL_MIN}
        print(f"  details (never verbs): {len(details)} words, e.g. "
              + ", ".join(sorted(details, key=lambda t: -with_slots[t])[:8]))

        out_actions = {}
        for aname, a in (conn.get("actions") or {}).items():
            api = a.get("api", "")
            op = ops.get(api)
            status = "ok" if op else ("NOT IN SPEC" if spec else "spec not read")
            learn = a.get("learn_from") or {}
            arows = [r for src, r in rows if intent_of(r) in (learn.get(src) or [])]
            tok_act = Counter()
            for r in arows:
                for tok in set(re.findall(r"[a-z']+", r["text"])):
                    tok_act[tok] += 1
            verbs = {}
            for tok, h in tok_act.items():
                if (h >= VERB_MIN_HITS and len(tok) > 1 and tok not in details
                        and h / tok_all[tok] >= VERB_MIN):
                    verbs[tok] = {"share": round(h / tok_all[tok], 3), "seen": tok_all[tok],
                                  "hits": h, "basis": "measured"}
            for w in (a.get("words") or []):
                w = w.lower()
                if w in verbs:
                    continue
                pat = matcher(w)
                seen = sum(1 for _, r in rows if pat.search(r["text"]))
                hit = sum(1 for r in arows if pat.search(r["text"]))
                share = round(hit / seen, 3) if arows and seen >= MIN_SEEN else None
                verbs[w] = {"share": share, "seen": seen, "basis": "yours"}
            # common and strongly on this side: most common first, then your own words
            measured = sorted(((w, v) for w, v in verbs.items() if v["basis"] == "measured"),
                              key=lambda kv: -kv[1]["hits"])[:VERB_MAX]
            yours = [(w, v) for w, v in verbs.items() if v["basis"] == "yours"]
            verbs = dict(measured + yours)
            out_actions[aname] = {
                "api": api, "spec": status,
                "summary": (op or {}).get("summary"),
                "params": [p.get("name") for p in (op or {}).get("parameters", [])],
                "needs": a.get("needs") or {},
                "objects": [o.lower() for o in (a.get("objects") or [])],
                "sentences": len(arows),
                "verbs": verbs,
            }
            top = ", ".join(f"{w} {v['share']:.0%}" if v["share"] is not None else f"{w} (yours)"
                            for w, v in list(verbs.items())[:10])
            print(f"  {aname:9} {api:26} [{status}] {len(arows):>4} sentences: {top}")

        out = {"service": sname, "topic": conn.get("topic"),
               "generated": time.strftime("%Y-%m-%d %H:%M"),
               "spec_read": bool(spec), "defaults": conn.get("defaults") or {},
               "actions": out_actions}
        with open(os.path.join(ACTIONS_DIR, f"{sname}.yaml"), "w") as f:
            f.write(GENERATED)
            yaml.safe_dump(out, f, sort_keys=False, allow_unicode=True, width=100)
        print(f"  wrote {ACTIONS_DIR}/{sname}.yaml")


# ---------- labels ----------

def labels():
    data = load_all_sources()
    learned = {t: find_labels(t, c or {}, data) for t, c in declared_topics().items()}
    for n, rows in data.items():
        print(f"\n=== {n} ===")
        for label, count in Counter(r["label"] for r in rows).most_common():
            who = [t for t, l in learned.items() if label in l.get(n, [])]
            print(f"  {label:28} {count:>6}   {'-> ' + ', '.join(who) if who else ''}")


# ---------- refresh ----------

def refresh(only=None):
    for name, src in SOURCES.items():
        if only and name != only:
            continue
        dest = os.path.expanduser(src["local"])
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        print(f"  {name}: downloading {src['url']}")
        if src.get("extract"):
            with tempfile.TemporaryDirectory() as tmp:
                archive = os.path.join(tmp, "archive.tar.gz")
                urllib.request.urlretrieve(src["url"], archive)
                with tarfile.open(archive) as tar:
                    member = tar.getmember(src["extract"])
                    with tar.extractfile(member) as fin, open(dest, "wb") as fout:
                        fout.write(fin.read())
        else:
            urllib.request.urlretrieve(src["url"], dest)
        print(f"    -> {dest}")


