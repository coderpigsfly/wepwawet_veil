# veil/flairlines.py - her flair lines, and how they move (decided Oct 14, Persona Flair page):
#
#   Lines from her books   personality/candidates/<who>.yaml   (tools/build_flair.py mine <who>)
#        | Accept: moves it straight in (gone from the books list; combing never brings it back)
#   Lines bank             personality/<who>.yaml flourishes   (edit, save or delete each)
#
# The Approved step in between was dropped the same evening (your call: the bank is edited line by
# line, so nothing needs to wait). Lines approved before move into the bank at start-up
# (approved_into_bank). personality/approved/<who>.yaml keeps only dropped: the book lines you
# deleted from the bank, so combing again leaves them out. Lines match by their words, case aside,
# and by the book's own wording (found) when they were reworded.

import os

import yaml

from veil import config, util

PERS = config.path("personality")


def key(text):
    return util.squash(text, lower=True)


def _file(*parts):
    return os.path.join(PERS, *parts)


# ---------- the lines bank: personality/<who>.yaml flourishes (comments kept) ----------

def bank(who):
    try:
        return config.plain((config.load_yaml(_file(f"{who}.yaml")) or {}).get("flourishes") or [])
    except FileNotFoundError:
        return []


def lines_seq(lines):
    """Flourishes as the personality file writes them: each a map, its topics and moods on one line."""
    from ruamel.yaml.comments import CommentedMap, CommentedSeq
    seq = CommentedSeq()
    for f in lines:
        m = CommentedMap((k, f[k]) for k in ("text", "slot", "topics", "mood", "from", "found", "placeholder")
                         if f.get(k) not in (None, "", False))
        for k in ("topics", "mood"):
            m[k] = config.flow_list(m.get(k) or (["any"] if k == "topics" else ["plain"]))
        seq.append(m)
    return seq


def save_bank(who, lines):
    header = (f"# personality/{who}.yaml - {who.title()}'s flair. Read by flair.py; edited on the Persona Flair page.\n"
              "# (See defaults/examples/personality/assistant.yaml for what each knob means.)")

    def change(doc):
        doc.setdefault("rate", 0)
        doc.setdefault("max_in_a_row", 1)
        doc["flourishes"] = lines_seq(lines)
    config.edit_yaml(_file(f"{who}.yaml"), change, header=header)


# ---------- approved: personality/approved/<who>.yaml (flourishes, and dropped) ----------

def approved_doc(who):
    try:
        with open(_file("approved", f"{who}.yaml")) as f:
            doc = yaml.safe_load(f) or {}
    except FileNotFoundError:
        doc = {}
    return {"flourishes": doc.get("flourishes") or [], "dropped": doc.get("dropped") or []}


def save_approved(who, doc):
    head = (f"# personality/approved/{who}.yaml - dropped: lines from her books you deleted from her lines\n"
            f"# bank (personality/{who}.yaml), so combing the books again leaves them out. (flourishes: is\n"
            f"# empty since Oct 14: accepted lines go straight into her lines bank.)\n\n")
    config.make_dirs(_file("approved"))
    config.write_text(_file("approved", f"{who}.yaml"),
                      head + yaml.safe_dump({"flourishes": doc["flourishes"], "dropped": doc["dropped"]},
                                            sort_keys=False, allow_unicode=True, width=200) + "\n\n")


# ---------- lines from her books: personality/candidates/<who>.yaml ----------

CANDIDATES_HEAD = ("# personality/candidates/{who}.yaml - GENERATED by tools/build_flair.py mine {who}\n"
                   "# Lines from her books, best guesses first. Accept one on the Persona Flair page and it moves into\n"
                   "# her lines bank (and leaves this list); combing again never brings back a line already in\n"
                   "# her lines bank, or dropped. 'found' is the book's wording.\n")


def candidates(who):
    try:
        with open(_file("candidates", f"{who}.yaml")) as f:
            return (yaml.safe_load(f) or {}).get("candidates") or []
    except FileNotFoundError:
        return []


def save_candidates(who, cands):
    import json
    lines = [CANDIDATES_HEAD.format(who=who), "\ncandidates:\n" if cands else "\ncandidates: []\n"]
    for c in cands:
        keep = "yes" if str(c.get("keep")).lower() in ("yes", "true") else "no"
        lines.append(f"- keep: {keep}\n"
                     f"  text: {json.dumps(c.get('text', ''), ensure_ascii=False)}\n"
                     f"  slot: {c.get('slot', 'opener')}\n"
                     f"  topics: [{', '.join(c.get('topics') or ['any'])}]\n"
                     f"  mood: [{', '.join(c.get('mood') or ['plain'])}]\n"
                     f"  from: {json.dumps(c.get('from', ''), ensure_ascii=False)}\n"
                     f"  found: {json.dumps(c.get('found', c.get('text', '')), ensure_ascii=False)}\n")
    config.make_dirs(_file("candidates"))
    config.write_text(_file("candidates", f"{who}.yaml"), "".join(lines) + "\n\n")


# ---------- what's already been taken out of the books ----------

def taken(who):
    """Every line already accepted, in her bank or dropped (its words and its book wording), so
    combing again leaves it out."""
    out = set()
    a = approved_doc(who)
    for f in a["flourishes"] + bank(who):
        out.add(key(f.get("text")))
        if f.get("found"):
            out.add(key(f["found"]))
    out.update(key(x) for x in a["dropped"])
    out.discard("")
    return out


def as_line(c):
    """A candidate (or any line) as a flair line: words, where, which answers, mood, and its book."""
    out = {"text": " ".join(str(c.get("text") or "").split()), "slot": str(c.get("slot") or "opener"),
           "topics": list(c.get("topics") or ["any"]), "mood": list(c.get("mood") or ["plain"])}
    if c.get("from"):
        out["from"] = str(c["from"])
    found = c.get("found") or c.get("text")
    if found:
        out["found"] = " ".join(str(found).split())
    if c.get("placeholder"):
        out["placeholder"] = True
    return out


def accept(who, found, changes=None):
    """A line from her books moves into her lines bank (with any slot or mood changed on the page).
    Returns the line, or None if it isn't in the books list any more."""
    cands = candidates(who)
    k = key(found)
    for i, c in enumerate(cands):
        if key(c.get("found", c.get("text"))) == k:
            line = as_line(dict(c, **(changes or {})))
            cands.pop(i)
            add_to_bank(who, [line])
            save_candidates(who, cands)
            return line
    return None


def accept_kept(who):
    """tools/build_flair.py approve: every keep: yes line moves into her lines bank, as Accept does.
    Returns how many moved."""
    n = 0
    for c in [c for c in candidates(who) if str(c.get("keep")).lower() in ("yes", "true")]:
        if accept(who, c.get("found", c.get("text"))):
            n += 1
    return n


def clear_candidates(who):
    """Empty the books list (combing again fills it, leaving out what's been taken)."""
    n = len(candidates(who))
    save_candidates(who, [])
    return n


def approved_into_bank(who):
    """Lines approved before the Approved step was dropped move into her lines bank (once; what she
    says doesn't change). Returns how many moved."""
    a = approved_doc(who)
    if not a["flourishes"]:
        return 0
    n = add_to_bank(who, [as_line(f) for f in a["flourishes"] if str(f.get("text") or "").strip()])
    a["flourishes"] = []
    save_approved(who, a)
    return n


def dropped_add(who, text):
    a = approved_doc(who)
    if key(text) not in {key(x) for x in a["dropped"]}:
        a["dropped"].append(text)
        save_approved(who, a)


def edit_bank(who, index, text_was, line=None):
    """Save (line) or delete (None) one line of her lines bank. Returns the bank."""
    lines = bank(who)
    if not 0 <= index < len(lines) or key(lines[index].get("text")) != key(text_was):
        raise LookupError("Her lines bank changed meanwhile (reload the page)")
    if line is None:
        gone = lines.pop(index)
        if gone.get("found"):           # a line from her books: combing again leaves it out
            dropped_add(who, gone["found"])
    else:
        lines[index] = dict(lines[index], **{k: line[k] for k in ("text", "slot", "topics", "mood")})
    save_bank(who, lines)
    return lines


def add_to_bank(who, new_lines):
    """Lines typed on the page, into her lines bank (ones she has already left out). Returns how many."""
    lines = bank(who)
    have = {key(f.get("text")) for f in lines}
    n = 0
    for f in new_lines:
        if key(f["text"]) in have:
            continue
        lines.append(f)
        have.add(key(f["text"]))
        n += 1
    if n:
        save_bank(who, lines)
    return n
